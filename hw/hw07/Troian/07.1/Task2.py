
def area_of_rectangle(length,width):
    """
    calculete and return area for rectangle
    """
    return length*width

def area_of_triangle(base,vertical_height):
    """
    calculete and return area for triangle
    """
    return 0.5*base*vertical_height

def area_of_circle(radius):
    """
    calculete and return area for circle
    """
    return 3.14159*(radius*radius)


