from math import pow, pi

def function_rectangle_area(a, b):
    """Calculate the area of a rectangle."""
    return a * b

def function_triangle_area(h, a):
    """Calculate the area of a triangle."""
    return 0.5 * h * a

def function_circle_area(r):
    """Calculate the area of a circle."""
    return pi * pow(r, 2)

